@main.command()
@click.argument("source")
@click.option(
    "--api-url", default="http://localhost:10946", show_default=True, help="Dewie API base URL."
)
@click.option(
    "--api-key",
    default=None,
    envvar="DEWIE_API_KEY",
    help="API key (or set DEWIE_API_KEY env var).",
)
@click.option("--source-name", default=None, help="Corpus / source label.")
@click.option("--wait/--no-wait", default=False, help="Wait for enrichment to complete.")
def ingest(
    source: str, api_url: str, api_key: str | None, source_name: str | None, wait: bool
) -> None:
    """
    Ingest a URL or local file path into the Dewie corpus.

    SOURCE can be a URL (https://...) or a local file path.
    """
    _require("httpx", "pip install dewie")
    import httpx  # noqa: PLC0415

    headers: dict[str, str] = {}
    if api_key:
        headers["X-API-Key"] = api_key

    payload: dict[str, object] = {}
    if source.startswith("http://") or source.startswith("https://"):
        payload["url"] = source
    else:
        # Local file — read and POST as body_text
        if not os.path.exists(source):
            click.echo(f"❌  File not found: {source}", err=True)
            sys.exit(1)
        with open(source) as f:
            content = f.read()
        payload["body_text"] = content
        payload["url"] = f"file://{os.path.abspath(source)}"
        payload["title"] = os.path.basename(source)

    if source_name:
        payload["source"] = source_name

    click.echo(f"📥  Ingesting: {source}")
    try:
        with httpx.Client(timeout=30) as client:
            r = client.post(f"{api_url}/api/user/ingest", json=payload, headers=headers)
            r.raise_for_status()
            data = r.json()
    except httpx.HTTPStatusError as e:
        click.echo(f"❌  API error {e.response.status_code}: {e.response.text[:200]}", err=True)
        sys.exit(1)
    except httpx.RequestError as e:
        click.echo(f"❌  Could not reach Dewie at {api_url}: {e}", err=True)
        sys.exit(1)

    doc_id = data.get("doc_id") or data.get("id", "?")
    status = data.get("status", "unknown")
    click.echo(f"✅  Ingested — doc_id: {doc_id}, status: {status}")

    if wait:
        import time  # noqa: PLC0415

        click.echo("⏳  Waiting for enrichment...")
        for _ in range(60):  # max 5 min
            time.sleep(5)
            try:
                with httpx.Client(timeout=10) as client:
                    r = client.get(f"{api_url}/api/documents/{doc_id}", headers=headers)
                    doc = r.json()
                    doc_status = doc.get("status", "unknown")
                    click.echo(f"   status: {doc_status}")
                    if doc_status in ("ready", "failed", "terminal"):
                        break
            except Exception:
                pass
        click.echo(f"✅  Final status: {doc_status}")


