# ── serve ─────────────────────────────────────────────────────────────────────


@main.command()
@click.option("--host", default="0.0.0.0", show_default=True, help="Bind host.")
@click.option("--port", default=10946, show_default=True, help="Bind port.")
@click.option("--workers", default=1, show_default=True, help="Uvicorn worker count.")
@click.option("--reload", is_flag=True, default=False, help="Enable auto-reload (dev mode).")
@click.option(
    "--config-dir", default=".", show_default=True, help="Directory containing dewie.yml."
)
def serve(host: str, port: int, workers: int, reload: bool, config_dir: str) -> None:
    """Start the Dewie API server on HOST:PORT.

    Config priority (highest to lowest):
      1. Environment variables (POSTGRES_DSN)
      2. dewie.yml (postgres_dsn field)
      3. Default SQLite database (./dewie.db)
    """
    _require("uvicorn", "pip install dewie")
    _require("fastapi", "pip install dewie")

    # Load .env file if present (e.g. from `dewie init` or hand-written).
    # This must happen before _bridge_dewie_yml_to_env so env vars take priority.
    try:
        from dotenv import load_dotenv as _load_dotenv
        _load_dotenv()
    except ImportError:
        pass

    # Bridge secrets and DB URL from dewie.yml into os.environ for the app process.
    # The app reads these directly from os.environ (not Settings), so they must be set here.
    _bridge_dewie_yml_to_env(config_dir)

    import uvicorn  # noqa: PLC0415

    click.echo(f"🚀  Starting Dewie on http://{host}:{port}")
    uvicorn.run(
        "dewie.main:app",
        host=host,
        port=port,
        workers=workers if not reload else 1,
        reload=reload,
        log_level="info",
    )


# ── init ──────────────────────────────────────────────────────────────────────


@main.command()
@click.option("--db-url", default=None, help="Database URL (default: SQLite at ./dewie.db).")
@click.option("--config-dir", default=".", show_default=True, help="Directory to write config.")
def init(db_url: str | None, config_dir: str) -> None:
    """Initialize config file and create DB schema."""
    import textwrap  # noqa: PLC0415

    config_path = os.path.join(config_dir, "dewie.yml")
    resolved_db = db_url or f"sqlite+aiosqlite:///{os.path.abspath('dewie.db')}"

    if not os.path.exists(config_path):
        import secrets as _secrets  # noqa: PLC0415
        generated_admin_key = f"dw_{_secrets.token_urlsafe(24)}"
        generated_jwt_secret = _secrets.token_hex(32)
        generated_service_key = _secrets.token_hex(32)

        config_content = textwrap.dedent(f"""\
            # Dewie configuration
            # Generated by `dewie init`

            postgres_dsn: "{resolved_db}"
            redis_url: ""
            enrichment_default_backend: "passthrough"
            api_host: "0.0.0.0"
            api_port: 10946
            api_workers: 1
            auth_enabled: false
            admin_key: "{generated_admin_key}"
            jwt_secret: "{generated_jwt_secret}"
            internal_service_key: "{generated_service_key}"
        """)
        with open(config_path, "w") as f:
            f.write(config_content)
        click.echo(f"✅  Config written to {config_path}")
        click.echo("")
        click.echo(f"   Admin key:   {generated_admin_key}")
        click.echo(f"   JWT secret:  {generated_jwt_secret[:16]}…  (full value in dewie.yml)")
        click.echo("")
        click.echo("   Save these. Auth is off by default — set auth_enabled: true in dewie.yml for production.")
    else:
        click.echo(f"ℹ️   Config already exists at {config_path} — skipping.")

    os.environ["POSTGRES_DSN"] = resolved_db
    asyncio.run(_init_db(resolved_db))
    click.echo("")
    click.echo("✅  Database ready.")
    click.echo("")
    click.echo("Next steps:")
    click.echo("  dewie admin-user   # create your admin account")
    click.echo("  dewie serve        # start the server")


