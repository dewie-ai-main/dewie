@main.command()
@click.option(
    "--api-url", default="http://localhost:10946", show_default=True, help="Dewie API base URL."
)
@click.option(
    "--api-key",
    default=None,
    envvar="DEWIE_API_KEY",
    help="API key (or set DEWIE_API_KEY env var).",
)
def status(api_url: str, api_key: str | None) -> None:
    """Show Dewie pipeline health: workers, doc counts, enrichment queue."""
    _require("httpx", "pip install dewie")
    import httpx  # noqa: PLC0415

    headers: dict[str, str] = {}
    if api_key:
        headers["X-API-Key"] = api_key

    try:
        with httpx.Client(timeout=10) as client:
            health = client.get(f"{api_url}/health", headers=headers)
            health.raise_for_status()
            h = health.json()
    except Exception as e:
        click.echo(f"❌  Dewie not reachable at {api_url}: {e}", err=True)
        sys.exit(1)

    click.echo(f"\n🟢  Dewie is {'live' if h.get('status') == 'ok' else 'degraded'} at {api_url}\n")

    # Try pipeline worker + error endpoints
    try:
        with httpx.Client(timeout=10) as client:
            workers = client.get(f"{api_url}/pipeline/workers/status", headers=headers)
            errors = client.get(f"{api_url}/pipeline/errors?window=60", headers=headers)

            if workers.status_code == 200:
                w = workers.json()
                click.echo(f"  Workers running: {w.get('running', '?')} / {w.get('total', '?')}")
                click.echo(f"  Workers paused:  {w.get('paused', '?')}")

            if errors.status_code == 200:
                e = errors.json()
                click.echo(f"  Error rate (60m): {e.get('error_rate', '?')}")
                click.echo(f"  Unresolved errs:  {e.get('unresolved_count', '?')}")

            if workers.status_code != 200 and errors.status_code != 200:
                click.echo(f"  API status: {h.get('status', 'unknown')}")
    except Exception:
        click.echo(f"  API status: {h.get('status', 'unknown')}")

    click.echo()


