async def _init_db(dsn: str) -> None:
    """Create or update DB schema using PostgresClient.init_schema."""
    try:
        from dewie.storage.postgres import PostgresClient  # noqa: PLC0415

        pg = PostgresClient(dsn=dsn)
        await pg.init_schema()
        await pg.close()
        click.echo("✅  DB schema initialized.")
    except Exception as exc:
        raise click.ClickException(f"Database initialization failed: {exc}") from exc


def _bridge_dewie_yml_to_env(config_dir: str) -> None:
    """Load dewie.yml and push key values into os.environ if not already set.

    The app reads POSTGRES_DSN, ADMIN_KEY, JWT_SECRET, and INTERNAL_SERVICE_KEY
    directly from os.environ, so they must be wired here before uvicorn launches.
    """
    config_path = os.path.join(config_dir, "dewie.yml")
    yml: dict = {}
    if os.path.exists(config_path):
        try:
            import yaml  # noqa: PLC0415
            with open(config_path) as f:
                yml = yaml.safe_load(f) or {}
        except Exception:
            pass

    # DB — prefer new field name, fall back to old one
    discrete_postgres_env = any(
        os.environ.get(var)
        for var in ("POSTGRES_HOST", "POSTGRES_PORT", "POSTGRES_USER", "POSTGRES_PASSWORD", "POSTGRES_DB")
    )
    if not os.environ.get("POSTGRES_DSN") and not discrete_postgres_env:
        db = yml.get("postgres_dsn") or yml.get("dewie_db")
        if db:
            os.environ["POSTGRES_DSN"] = str(db).strip()
        else:
            os.environ["POSTGRES_DSN"] = f"sqlite+aiosqlite:///{os.path.abspath('dewie.db')}"

    # Secrets — only set if not already in environment
    for env_var, yml_key in (
        ("ADMIN_KEY",             "admin_key"),
        ("JWT_SECRET",            "jwt_secret"),
        ("INTERNAL_SERVICE_KEY",  "internal_service_key"),
    ):
        if not os.environ.get(env_var) and yml.get(yml_key):
            os.environ[env_var] = str(yml[yml_key]).strip()


def _read_db_from_dewie_yml(config_dir: str) -> str | None:
    """Read postgres_dsn from dewie.yml when available.

    Supports both old dewie_db field and new postgres_dsn field for backward compatibility.
    Priority: postgres_dsn > dewie_db
    """
    config_path = os.path.join(config_dir, "dewie.yml")
    if not os.path.exists(config_path):
        return None

    try:
        import yaml  # noqa: PLC0415

        with open(config_path) as f:
            data = yaml.safe_load(f) or {}

        # Try new field first (postgres_dsn), then fallback to old field (dewie_db)
        db = data.get("postgres_dsn") or data.get("dewie_db")
        return str(db).strip() if db else None
    except Exception:
        return None


_MISSING = object()


def _config_path(config_dir: str) -> Path:
    return Path(config_dir) / "dewie.yml"


def _load_config(path: Path) -> dict[str, Any]:
    _require("yaml", "pip install pyyaml")
    import yaml  # noqa: PLC0415

    if not path.exists():
        return {}
    loaded = yaml.safe_load(path.read_text())
    return loaded if isinstance(loaded, dict) else {}


def _save_config(path: Path, data: dict[str, Any]) -> None:
    _require("yaml", "pip install pyyaml")
    import yaml  # noqa: PLC0415

    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(yaml.safe_dump(data, sort_keys=True), encoding="utf-8")
    tmp.replace(path)


def _get_nested(data: dict[str, Any], dotted_path: str) -> Any:
    cur: Any = data
    for part in dotted_path.split("."):
        if not isinstance(cur, dict) or part not in cur:
            return _MISSING
        cur = cur[part]
    return cur


def _set_nested(data: dict[str, Any], dotted_path: str, value: Any) -> None:
    parts = dotted_path.split(".")
    cur: dict[str, Any] = data
    for part in parts[:-1]:
        nxt = cur.get(part)
        if not isinstance(nxt, dict):
            nxt = {}
            cur[part] = nxt
        cur = nxt
    cur[parts[-1]] = value


def _coerce_config_value(raw: str, value_type: str) -> Any:
    value_type = value_type.lower()
    if value_type == "str":
        return raw
    if value_type == "int":
        return int(raw)
    if value_type == "float":
        return float(raw)
    if value_type == "bool":
        norm = raw.strip().lower()
        if norm in {"1", "true", "yes", "on"}:
            return True
        if norm in {"0", "false", "no", "off"}:
            return False
        raise click.ClickException(f"Invalid bool value: {raw}")
    if value_type == "json":
        return json.loads(raw)

    norm = raw.strip().lower()
    if norm in {"true", "false"}:
        return norm == "true"
    try:
        return int(raw)
    except ValueError:
        pass
    try:
        return float(raw)
    except ValueError:
        pass
    if raw.startswith("{") or raw.startswith("["):
        try:
            return json.loads(raw)
        except Exception:
            return raw
    return raw


def _import_env_file(path: Path, data: dict[str, Any]) -> int:
    if not path.exists():
        raise click.ClickException(f"Env file not found: {path}")

    mapping = {
        "POSTGRES_DSN": "postgres_dsn",
        "DEWIE_DB": "postgres_dsn",  # Map old DEWIE_DB env var to postgres_dsn for backward compat
        "REDIS_URL": "redis_url",
        "AUTH_ENABLED": "auth_enabled",
        "QUERY_DEFAULT_RANKER": "query_default_ranker",
        "CHAT_SERVER_AQ": "chat_server_aq",
        "CHAT_MODEL_AQ": "chat_model_aq",
        "CHAT_SERVER_KE": "chat_server_ke",
        "CHAT_MODEL_KE": "chat_model_ke",
        "EMBED_SERVER": "embed_server",
        "EMBED_MODEL": "embed_model",
        "ENRICHMENT_MODEL": "enrichment_model",
        "EMBEDDING_MODEL": "embedding_model",
    }

    imported = 0
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip().strip('"').strip("'")
        target = mapping.get(key)
        if not target:
            continue
        _set_nested(data, target, _coerce_config_value(value, "auto"))
        imported += 1
    return imported


@main.command("install")
@click.argument("harness", type=click.Choice(["openclaw"]))
@click.option("--api-url", default="http://localhost:10946", show_default=True, help="Dewie API URL reachable from the harness.")
@click.option("--db-url", default=None, envvar="POSTGRES_DSN", help="Database URL (or set POSTGRES_DSN). If not set, uses dewie.yml.")
@click.option("--workspace-dir", default=None, help="OpenClaw workspace dir (default: ~/.openclaw/workspace).")
@click.option("--key-name", default="dewie-install", show_default=True, help="Label stored on the created API key.")
@click.option("--force", is_flag=True, default=False, help="Overwrite an existing skill file that differs from the canonical one.")
@click.option("--dry-run", is_flag=True, default=False, help="Print what would happen without writing anything.")
def install(
    harness: str,
    api_url: str,
    db_url: str | None,
    workspace_dir: str | None,
    key_name: str,
    force: bool,
    dry_run: bool,
) -> None:
    """Set up Dewie as an MCP server for a coding-agent harness."""
    from dewie import install_openclaw as inst

    if not db_url:
        db_url = _read_db_from_dewie_yml(".")
    if not db_url:
        db_url = "postgresql+asyncpg://dewie:dewie@localhost:5432/dewie"  # Dev-only default — do not use in production

    workspace = Path(workspace_dir) if workspace_dir else inst.default_workspace_dir()

    try:
        if dry_run:
            click.echo("(dry run — no API key created, no files written)")
            click.echo(f"Would register: {inst.register_mcp_server(api_url, '<api-key>', dry_run=True)}")
            click.echo(f"Skill file: {workspace / 'skills' / 'dewie' / 'SKILL.md'} ({inst.write_skill_file(workspace, force=force, dry_run=True)})")
            return

        raw_key = asyncio.run(inst.create_key(db_url, key_name))
        click.echo(f"✅  Created API key: {raw_key}  (shown once — store it now)")

        cmd = inst.register_mcp_server(api_url, raw_key)
        click.echo(f"✅  Registered with OpenClaw: {cmd}")

        skill_result = inst.write_skill_file(workspace, force=force)
        click.echo(f"✅  Skill file {skill_result}: {workspace / 'skills' / 'dewie' / 'SKILL.md'}")

        check = asyncio.run(inst.self_check(api_url, raw_key))
        click.echo(f"✅  Self-check passed: {check}")
    except inst.InstallError as exc:
        raise click.ClickException(str(exc)) from exc


@main.command("admin-user")
@click.option(
    "--username",
    "--email",  # backward-compat alias; email not required
    "username",
    prompt="Admin username",
    help="Username for admin account (email address not required).",
)
@click.option(
    "--password",
    prompt=True,
    hide_input=True,
    confirmation_prompt=True,
    help="Password for admin account (min 8 characters)",
)
@click.option(
    "--db-url",
    default=None,
    envvar="POSTGRES_DSN",
    help="Database URL (or set POSTGRES_DSN env var). If not set, uses dewie.yml or default.",
)
def admin_user(username: str, password: str, db_url: str | None) -> None:
    """Create or update the admin user account. The username does not need to be an email address."""
    # Load DB URL from dewie.yml if not provided
    if not db_url:
        db_url = _read_db_from_dewie_yml(".")
    if not db_url:
        db_url = "postgresql+asyncpg://dewie:dewie@localhost:5432/dewie"  # Dev-only default — do not use in production

    # Validate password
    if len(password) < 8:
        raise click.ClickException("Password must be at least 8 characters")

    # Create/update admin user
    try:
        asyncio.run(_create_or_update_admin(db_url, username, password))
        click.echo(f"✅  Admin user created/updated: {username}")
    except Exception as exc:
        raise click.ClickException(f"Failed to create admin user: {exc}") from exc


async def _create_or_update_admin(db_url: str, username: str, password: str) -> None:
    """Create or update admin user in the database."""
    import uuid

    from sqlalchemy import text

    from dewie.local_auth import hash_password
    from dewie.storage.postgres import PostgresClient

    pg = PostgresClient(dsn=db_url)

    password_hash = hash_password(password)

    async with pg._engine.begin() as conn:
        # Try to update existing user
        result = await conn.execute(
            text(
                "UPDATE users "
                "SET email = :email, password_hash = :hash, is_admin = true "
                "WHERE email = :old_email "
                "RETURNING id"
            ),
            {"email": username, "hash": password_hash, "old_email": username},
        )

        if result.rowcount > 0:
            await pg.close()
            return

        # Create new admin user
        await conn.execute(
            text(
                """
                INSERT INTO users (
                    id, tenant_id, email, name, password_hash,
                    is_admin, plan, activation_status, created_at
                )
                VALUES (
                    :id, :tenant_id, :email, :name, :password_hash,
                    true, 'unlimited', 'approved', now()
                )
                """
            ),
            {
                "id": str(uuid.uuid4()),
                "tenant_id": "00000000-0000-0000-0000-000000000001",
                "email": username,
                "name": "Admin",
                "password_hash": password_hash,
            },
        )

    await pg.close()


