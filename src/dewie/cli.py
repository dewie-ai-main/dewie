@main.command()
@click.option(
    "--input",
    "input_file",
    required=True,
    type=click.Path(exists=True),
    help="Input JSONL/JSON file path.",
)
@click.option(
    "--corpus",
    "corpus_id",
    required=True,
    help="Target corpus ID for import.",
)
@click.option(
    "--api-url", default="http://localhost:10946", show_default=True, help="Dewie API base URL."
)
@click.option(
    "--api-key",
    default=None,
    envvar="DEWIE_API_KEY",
    help="API key (or set DEWIE_API_KEY env var).",
)
@click.option(
    "--skip-duplicates/--upsert-duplicates",
    default=True,
    help="Strategy for handling duplicate document IDs.",
)
def import_cmd(
    input_file: str, corpus_id: str, api_url: str, api_key: str | None, skip_duplicates: bool
) -> None:
    """Import documents from a JSONL/JSON file into a corpus."""
    _require("httpx", "pip install dewie")
    import httpx  # noqa: PLC0415

    headers: dict[str, str] = {"Content-Type": "application/json"}
    if api_key:
        headers["X-API-Key"] = api_key

    click.echo(f"📥  Importing {input_file} into corpus {corpus_id}")

    batch_size = 100
    processed = 0
    skipped = 0
    errors = 0

    try:
        with open(input_file) as f:
            content = f.read().strip()

        if not content:
            click.echo("⚠️  Input file is empty")
            return

        if content.startswith("["):
            json_str = content
            if json_str.endswith(","):
                json_str = json_str[:-1] + "]"
            try:
                docs = json.loads(json_str)
            except json.JSONDecodeError as e:
                click.echo(f"❌  Invalid JSON: {e}", err=True)
                sys.exit(1)
        else:
            lines = content.split("\n")
            docs = []
            for line in lines:
                line = line.strip()
                if not line:
                    continue
                try:
                    docs.append(json.loads(line))
                except json.JSONDecodeError as e:
                    click.echo(f"⚠️  Skipping invalid line: {e}", err=True)
                    errors += 1

        total = len(docs)
        click.echo(f"   Found {total} documents to import")

        for i in range(0, total, batch_size):
            batch = docs[i : i + batch_size]
            payload = {
                "documents": batch,
                "corpus_id": corpus_id,
                "skip_duplicates": skip_duplicates,
            }
            try:
                with httpx.Client(timeout=60) as client:
                    r = client.post(f"{api_url}/documents/import", json=payload, headers=headers)
                    if r.status_code == 200:
                        result = r.json()
                        processed += len(batch)
                        skipped += result.get("skipped", 0)
                    else:
                        errors += len(batch)
            except httpx.RequestError as e:
                click.echo(f"⚠️  Batch {i // batch_size + 1} failed: {e}", err=True)
                errors += len(batch)

            if (i + batch_size) % 1000 == 0 or i + batch_size >= total:
                click.echo(f"   Processed {min(i + batch_size, total)}/{total} documents")

    except Exception as e:
        click.echo(f"❌  Import failed: {e}", err=True)
        sys.exit(1)

    click.echo(f"✅  Import complete: {processed} processed, {skipped} skipped, {errors} errors")


