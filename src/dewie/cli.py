def _require(package: str, install_hint: str = "") -> None:
    """Friendly error if an optional import is missing."""
    try:
        __import__(package)
    except ImportError:
        hint = install_hint or f"pip install {package}"
        print(f"❌  Missing dependency: {package!r}. Install with: {hint}", file=sys.stderr)
        sys.exit(1)


